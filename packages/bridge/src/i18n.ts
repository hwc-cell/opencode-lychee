export type BridgeLang = "zh" | "en"

export function bridgeLang(): BridgeLang {
  const raw = process.env.OPENCODE_LANG ?? process.env.LYCHEE_LANG ?? "zh"
  return raw.toLowerCase().startsWith("en") ? "en" : "zh"
}

